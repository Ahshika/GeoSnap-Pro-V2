const I18nEngine = {
  current: localStorage.getItem('geosnap_lang') || 'ar',
  t(key) {
    return (I18N[this.current] && I18N[this.current][key]) || I18N.ar[key] || key;
  },
  toggle() {
    this.current = this.current === 'ar' ? 'en' : 'ar';
    localStorage.setItem('geosnap_lang', this.current);
    this.apply();
  },
  apply() {
    const root = document.getElementById('html-root');
    root.lang = this.current;
    root.dir = this.current === 'ar' ? 'rtl' : 'ltr';

    document.querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = this.t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = this.t(el.getAttribute('data-i18n-placeholder'));
    });
  }
};
